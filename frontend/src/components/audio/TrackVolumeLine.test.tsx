/** A client point for the row point (x, y) of the track at `index`. */
const client = (index: number, x: number, y: number) => ({
  clientX: ORIGIN.x + x * Z,
  clientY: ORIGIN.y + (index * ROW + y) * Z,
});
/** A pointer event at a row point. Returns false when its default was prevented. */
const ptr = (el: Element, type: string, index: number, x: number, y: number, init: Record<string, unknown> = {}): boolean =>
  el.dispatchEvent(new win.PointerEvent(type, {
    bubbles: true, cancelable: true, pointerId: 1, pointerType: 'mouse', button: 0,
    buttons: type === 'pointerup' ? 0 : 1, ...client(index, x, y), ...init,
  }));
const mouse = (el: Element, type: string, index: number, x: number, y: number, init: Record<string, unknown> = {}): boolean =>
  el.dispatchEvent(new win.MouseEvent(type, {
    bubbles: true, cancelable: true, button: type === 'contextmenu' ? 2 : 0, ...client(index, x, y), ...init,
  }));
const key = (el: Element, k: string, init: Record<string, unknown> = {}): boolean =>
  el.dispatchEvent(new win.KeyboardEvent('keydown', { key: k, bubbles: true, cancelable: true, ...init }));
const valueSetter = Object.getOwnPropertyDescriptor(win.HTMLInputElement.prototype, 'value')!.set!;
const type = (el: HTMLInputElement, text: string) => {
  valueSetter.call(el, text);
  el.dispatchEvent(new win.InputEvent('input', { bubbles: true, inputType: 'insertText', data: text.slice(-1) }));
};

