  assert.equal(chip('t1')?.textContent, '-6.0 dB');
  assert.equal(undoSteps(), 1, 'a typed value is one undo step');
  assert.deepEqual(windowKeys, [], 'neither Enter reached the timeline');
  assert.deepEqual(sel().selected, { trackId: 't1', t: 2.5 }, 'the keyframe stays selected');

  // The chip opens the field too. Escape cancels.
  await step(() => { row('t1').querySelector('button')!.click(); });
