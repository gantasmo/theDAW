/* ── The harness: what WaveformEditor wires ─────────────────────────────────── */

/** What the line reported to the editor. */
const calls: Array<[string, ...unknown[]]> = [];
/** The volume report `i` handed to onFaderChange. */
const sentVolume = (i: number): number => calls[i][2] as number;
/** What reached the lanes container under the line. */
const seen: string[] = [];
/** The editor's snap grid in seconds, 0 for off. */
let grid = 0;

interface HarnessProps {
  /** false while the cut tool is active */
  interactive?: boolean;
  /** The part of the timeline in view, in seconds. All ten of them unless given. */
  fromSec?: number;
  toSec?: number;
}

function Harness({ interactive = true, fromSec = 0, toSec = WIDTH / ZOOM }: HarnessProps) {
  const tracks = useEditorStore((s) => s.tracks);
  const lanes = useEditorStore((s) => s.automationLanes);
  return (
    <div
      data-lanes=""
      onPointerDown={() => seen.push('pointerdown')}
      onContextMenu={() => seen.push('contextmenu')}
      onDoubleClick={() => seen.push('dblclick')}
      onPointerMove={() => seen.push('pointermove')}
      onPointerUp={() => seen.push('pointerup')}
    >
      <TrackVolumeLines
        tracks={tracks}
        lanes={lanes}
        zoom={ZOOM}
        trackHeight={ROW}
        width={WIDTH}
        fromSec={fromSec}
        toSec={toSec}
        interactive={interactive}
        snap={(sec) => (grid > 0 ? Math.round(sec / grid) * grid : sec)}
        timeStep={(coarse) => (coarse ? 1 : 0.25)}
        onFaderChange={(id, v) => {
          calls.push(['change', id, v]);
          useEditorStore.getState().updateTrack(id, { volume: v });
        }}
        onFaderGestureStart={(id) => calls.push(['start', id])}
        onFaderGestureEnd={(id) => calls.push(['end', id])}
        onKeyframeSelected={() => calls.push(['selected'])}
      />
    </div>
  );
}

