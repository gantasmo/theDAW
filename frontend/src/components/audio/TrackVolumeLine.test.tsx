/* ── CSS zoom ───────────────────────────────────────────────────────────────── */

// At 1920x1080 the shell's CSS zoom is 1.1, so a client point is the row's own
// point times 1.1. The line takes the zoom out: a keyframe lands under the
// pointer and a drag moves the value by what the pointer travelled on screen.
{
  await reset();
  Z = 1.1;
  await step(() => { host.style.zoom = String(Z); });
  await step(() => { mouse(hit('t2'), 'contextmenu', 1, 300, 59); });
  near(pointsOf('t2')[0].t, 3, 1e-9, 'the keyframe is at the time drawn under the pointer');
  const h = handle('t2', 0)!;
  await step(() => {
    ptr(h, 'pointerdown', 1, 300, 59);
    ptr(h, 'pointermove', 1, 300, 45);
    ptr(h, 'pointerup', 1, 300, 45);
  });
  near(pointsOf('t2')[0].v, 0.7, 1e-9, '14 row px up is +0.2, whatever the zoom');
  await step(() => { host.style.zoom = ''; });
  Z = 1;
}

