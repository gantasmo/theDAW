/**
 * Mount test for the EDIT track volume line (TrackVolumeLine.tsx), against the
 * real editor store and the real keyframe selection.
 *
 * The sequence a user makes: every track row draws a line at its fader's
 * level; a right-click on the line adds a keyframe there and selects it; a
 * keyframe drags in value and, once the drag goes sideways, in time, and one
 * undo takes the drag back; Escape during a drag takes it back at once; a drag
 * on a line with no keyframes moves the track fader between one gesture start
 * and one gesture end; the stretch between two keyframes drags as one; the
 * arrow keys nudge the selected keyframe, Delete removes it, Enter opens a
 * field that takes a typed dB value; a right-click on a keyframe opens its
 * menu; a press anywhere else drops the selection; with the cut tool active
 * nothing in the line takes the pointer.
 *
 * It also pins what is easy to get wrong: the line's wrapper and svg take no
 * pointer events, the hit line is one element in both states, every way a drag
 * can end runs one teardown that closes its undo group exactly once, a press
 * that never travels writes nothing, and the pointer math survives CSS zoom.
 *
 * Client-rendered (createRoot on jsdom), in the CcLane.test.tsx pattern.
 *
 *   cd frontend && node node_modules/tsx/dist/cli.mjs src/components/audio/TrackVolumeLine.test.tsx
 */
