/* ── Escape during a drag ───────────────────────────────────────────────────── */

// Escape takes the drag back and swallows the key: neither the line's own
// Escape (deselect) nor the timeline's runs as well.
{
  await reset([lane('t1', [{ t: 2.5, v: 0.8 }])]);
  const h = handle('t1', 0)!;
  await step(() => { ptr(h, 'pointerdown', 0, 250, 38); });
  await step(() => { ptr(h, 'pointermove', 0, 300, 52); });
  near(pointsOf('t1')[0].t, 3, 1e-9, 'dragged in time');
  near(pointsOf('t1')[0].v, 0.6, 1e-9, 'and in value');
  assert.equal(undoSteps(), 1);
  windowKeys.length = 0;
  let notPrevented = true;
  await step(() => { notPrevented = key(svg('t1'), 'Escape'); });
  assert.equal(notPrevented, false);
  assert.deepEqual(windowKeys, [], 'the key stops at the drag');
  assert.deepEqual(pointsOf('t1'), [{ t: 2.5, v: 0.8 }], 'the keyframe is back where it was');
  assert.equal(undoSteps(), 0, 'and the history is where it was');
  assert.deepEqual(groupLog, ['begin', 'end']);
  assert.deepEqual(sel().selected, { trackId: 't1', t: 2.5 }, 'the selection went back with it, and was not dropped');
  assert.equal(handles('t1').length, 1);
  // The button is still down. What it does now belongs to no drag.
  await step(() => {
    ptr(h, 'pointermove', 0, 320, 40);
    ptr(h, 'pointerup', 0, 320, 40);
  });
  assert.deepEqual(pointsOf('t1'), [{ t: 2.5, v: 0.8 }]);
  assert.deepEqual(groupLog, ['begin', 'end'], 'the group was closed once');

  // Escape on a press that has not travelled: nothing to take back, and still the drag's key.
  groupLog.length = 0;
  windowKeys.length = 0;
  await step(() => { ptr(h, 'pointerdown', 0, 250, 38); });
  await step(() => { key(svg('t1'), 'Escape'); });
  await step(() => { ptr(h, 'pointermove', 0, 250, 10); });
  assert.deepEqual(pointsOf('t1'), [{ t: 2.5, v: 0.8 }], 'the press was cancelled, so the move drags nothing');
  assert.deepEqual(groupLog, []);
  assert.deepEqual(windowKeys, []);
  await step(() => { ptr(h, 'pointerup', 0, 250, 10); });

  // Escape on a fader drag takes the fader back, between its one start and one end.
  calls.length = 0;
  await step(() => { ptr(hit('t2'), 'pointerdown', 1, 400, 59); });
  await step(() => { ptr(hit('t2'), 'pointermove', 1, 400, 45); });
  near(trackOf('t2').volume, 0.7, 1e-9, 'the fader is up');
  await step(() => { key(svg('t2'), 'Escape'); });
  assert.equal(trackOf('t2').volume, 0.5, 'and back');
  assert.deepEqual(calls.map((c) => c[0]), ['start', 'change', 'end']);
  await step(() => { ptr(hit('t2'), 'pointerup', 1, 400, 45); });
  assert.deepEqual(calls.map((c) => c[0]), ['start', 'change', 'end']);
}

