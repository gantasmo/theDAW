/* ── The page the line is drawn on ──────────────────────────────────────────── */

const ZOOM = 100; // px per second
const ROW = 104; // the default row height: the band is 24..94, 70 px tall
const WIDTH = 1000; // ten seconds of timeline
/** Where the lanes sit in the window, in client px. */
const ORIGIN = { x: 40, y: 30 };
/** The shell's CSS zoom. A client point is the row's own point times this. */
let Z = 1;

// jsdom lays nothing out, so the svg is given the rect a browser would report:
// the row's place in the lanes, scaled by the CSS zoom.
win.SVGSVGElement.prototype.getBoundingClientRect = function getRect(this: SVGSVGElement): DOMRect {
  const rowTop = parseFloat((this.parentElement as HTMLElement | null)?.style.top ?? '') || 0;
  const left = ORIGIN.x;
  const top = ORIGIN.y + rowTop * Z;
  const width = WIDTH * Z;
  const height = ROW * Z;
  return { left, top, width, height, right: left + width, bottom: top + height, x: left, y: top, toJSON: () => ({}) } as DOMRect;
};

// jsdom has no pointer capture. These stand-ins record who took it and who let go.
