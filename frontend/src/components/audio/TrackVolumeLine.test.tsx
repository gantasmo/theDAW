/* ── One teardown, however the drag ends ────────────────────────────────────── */

// A lost capture, a cancel, a release that lands off the line, the cut tool
// and an unmount all end the drag, and each closes its undo group exactly once.
{
  const oneDrag = async (end: () => void | Promise<void>) => {
    await reset([lane('t1', [{ t: 2.5, v: 0.8 }])]);
    const h = handle('t1', 0)!;
    await step(() => { ptr(h, 'pointerdown', 0, 250, 38); });
    await step(() => { ptr(h, 'pointermove', 0, 250, 52); });
    near(pointsOf('t1')[0].v, 0.6, 1e-9, 'the drag is in flight');
    assert.deepEqual(groupLog, ['begin']);
    await end();
    assert.deepEqual(groupLog, ['begin', 'end'], 'closed once');
    near(pointsOf('t1')[0].v, 0.6, 1e-9, 'what the drag wrote stays');
    // The group really is closed: two later edits are two undo steps.
    const steps = undoSteps();
    await step(() => {
      store().updateTrack('t2', { volume: 0.4 });
      beginUndoStep();
      store().updateTrack('t2', { volume: 0.3 });
    });
    assert.equal(undoSteps(), steps + 2);
    return h;
  };

  let h = await oneDrag(() => step(() => { handle('t1', 0)!.dispatchEvent(new win.PointerEvent('lostpointercapture', { bubbles: true, pointerId: 1 })); }));
  await step(() => { ptr(h, 'pointermove', 0, 250, 80); });
  near(pointsOf('t1')[0].v, 0.6, 1e-9, 'a move after the capture is lost drags nothing');
  assert.deepEqual(groupLog, ['begin', 'end']);

  await oneDrag(() => step(() => { ptr(handle('t1', 0)!, 'pointercancel', 0, 250, 52); }));

  // The release lands on something else: the capture was lost and nobody said so.
  await oneDrag(() => step(() => { win.document.body.dispatchEvent(new win.PointerEvent('pointerup', { bubbles: true, pointerId: 1 })); }));
  // Another pointer's release is not this drag's.
  await reset([lane('t1', [{ t: 2.5, v: 0.8 }])]);
  h = handle('t1', 0)!;
  await step(() => { ptr(h, 'pointerdown', 0, 250, 38); });
  await step(() => { ptr(h, 'pointermove', 0, 250, 52); });
  await step(() => { win.document.body.dispatchEvent(new win.PointerEvent('pointerup', { bubbles: true, pointerId: 2 })); });
  assert.deepEqual(groupLog, ['begin'], 'still dragging');
  await step(() => { ptr(h, 'pointerup', 0, 250, 52); });
  assert.deepEqual(groupLog, ['begin', 'end']);

  // The cut tool takes the pointer away mid-drag.
  await oneDrag(() => mount({ interactive: false }));
  await mount();

  // A press whose release was never seen ends when the next press comes.
  await reset([lane('t1', [{ t: 2.5, v: 0.8 }])]);
  h = handle('t1', 0)!;
  await step(() => { ptr(h, 'pointerdown', 0, 250, 38); });
  await step(() => { ptr(h, 'pointermove', 0, 250, 52); });
  await step(() => { ptr(hit('t2'), 'pointerdown', 1, 400, 59); });
  assert.deepEqual(groupLog, ['begin'], 'another line is another gesture');
  await step(() => { ptr(hit('t2'), 'pointerup', 1, 400, 59); });
  await step(() => { ptr(h, 'pointerdown', 0, 250, 52); });
  assert.deepEqual(groupLog, ['begin', 'end'], 'the same line: the stale drag is closed before the new press');
  await step(() => { ptr(h, 'pointerup', 0, 250, 52); });
  assert.deepEqual(groupLog, ['begin', 'end']);

  // The line leaves the page mid-drag (its track is deleted, EDIT closes).
  await reset();
  await step(() => { ptr(hit('t2'), 'pointerdown', 1, 400, 59); });
  await step(() => { ptr(hit('t2'), 'pointermove', 1, 400, 45); });
  assert.deepEqual(calls.map((c) => c[0]), ['start', 'change']);
  await step(() => root.unmount());
  assert.deepEqual(calls.map((c) => c[0]), ['start', 'change', 'end'], 'the fader gesture is ended');
  assert.deepEqual(groupLog, ['begin', 'end'], 'and its undo group closed, once');
  windowKeys.length = 0;
  await step(() => { key(win.document.body, 'Escape'); });
  assert.deepEqual(windowKeys, ['Escape'], 'the drag\'s Escape listener went with it');
  near(trackOf('t2').volume, 0.7, 1e-9, 'so Escape takes nothing back');

  root = createRoot(host);
  await mount();
}

